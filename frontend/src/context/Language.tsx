export type TextKey = keyof typeof TEXT

type Context = { lang: Lang; t: (key: TextKey) => string }
const LanguageContext = createContext<Context | null>(null)
const ENGLISH: Context = { lang: 'en', t: (key) => TEXT[key][0] }

export function LanguageProvider({ children }: { children: ReactNode }) {
  return <LanguageContext.Provider value={ENGLISH}>{children}</LanguageContext.Provider>
}

export function useLang() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLang must be used inside LanguageProvider')
  return context
}
